#!/bin/sh
set -eu

lazel=$(cd "$(dirname "$1")" && pwd)/$(basename "$1")
example=$(cd "$(dirname "$0")" && pwd)
workspace=$(mktemp -d)
trap 'rm -rf "$workspace"' EXIT
mkdir "$workspace/app" "$workspace/generator"
cp "$example/lazel.toml" "$workspace/"
cp "$example/app/app.py" "$example/app/build.py" "$workspace/app/"
cp "$example/generator/main.rs" "$workspace/generator/"
LAZEL_RUST_VERSION=$(rustc --version --verbose)
LAZEL_PYTHON_VERSION=$(python3 --version)
export LAZEL_RUST_VERSION LAZEL_PYTHON_VERSION
cd "$workspace"

verify() {
    directory=$1
    expected=$2
    output=$(cd "$directory" && "$lazel" run app:build 2>&1) || {
        printf '%s\n' "$output" >&2
        exit 1
    }
    printf '%s\n' "$output"
    test "$(printf '%s\n' "$output" | grep '^lazel:')" = "$expected"
    test -x generator/build/generate
    test "$(cat app/build/generated.txt)" = 'generated by Rust'
    test -s app/build/app.pyc
    test "$(python3 app/build/app.pyc)" = 'generated by Rust'
}

miss=$(printf 'lazel: cache miss generator:build\nlazel: running generator:build\nlazel: cache miss app:build\nlazel: running app:build')
hit=$(printf 'lazel: cache hit generator:build\nlazel: cache hit app:build')
verify . "$miss"
verify app "$hit"
rm -rf generator/build app/build
verify app "$hit"
printf '\n// Change the declared input.\n' >> generator/main.rs
verify . "$miss"
LAZEL_RUST_VERSION="$LAZEL_RUST_VERSION (changed)"
verify . "$miss"
